/**
 * دفتر خدمات سلامت ۴۷۷ — داده‌های بخش خدمات سلامت
 * =====================================================================
 * تنها منبع حقیقت محتوای بخش «خدمات سلامت» سایت. همه صفحات
 * (/health/ و /health/[slug]/) از همین فایل ساخته می‌شوند، بنابراین
 * افزودن خدمت، دوره یا سؤال جدید نیازی به تغییر کامپوننت‌ها ندارد.
 *
 * ⚠ محتوای نیازمند تأیید مدیریت
 * هر فیلدی که هنوز توسط مدیریت مجموعه تأیید نشده است در قالب
 * `ManagedField` با `approved: false` ذخیره می‌شود و در رابط کاربری با
 * برچسب «نیازمند تأیید مدیریت» نمایش داده می‌شود. پیش از انتشار نهایی،
 * مقادیر واقعی را جایگزین و `approved` را `true` کنید.
 *
 * ⚠ ادعای تأییدنشده ممنوع
 * هیچ مجوز، مدرک، گواهی یا اعتبار رسمی که تأیید نشده است به این مجموعه
 * نسبت داده نمی‌شود. متن‌های سلب مسئولیت (`disclaimer`) بخشی از محتوا هستند.
 */
