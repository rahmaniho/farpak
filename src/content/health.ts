/** وضعیت نمایش خدمت. خدمت غیرفعال در فهرست با برچسب ویژه و بدون فرم درخواست نمایش داده می‌شود. */
export type ServiceStatus = 'active' | 'inactive';

/** مقدار مدیریتی: تا زمانی که `approved` نادرست است با برچسب «نیازمند تأیید مدیریت» نمایش داده می‌شود. */
export interface ManagedField<T> {
  value: T;
  approved: boolean;
}

export interface Faq {
  q: string;
  a: string;
}

export interface Step {
  title: string;
  detail?: string;
}

/** گزینه‌های «نوع درخواست» در فرم هر خدمت. */
export interface RequestOption {
  value: string;
  label: string;
}

export type ExtraFieldType = 'text' | 'tel' | 'textarea' | 'select';

/** فیلد اختصاصی فرم یک خدمت (مثلاً «نام مجموعه» در قراردادهای ممیزی). */
export interface ExtraField {
  name: string;
  label: string;
  type: ExtraFieldType;
  required?: boolean;
  placeholder?: string;
  hint?: string;
  options?: RequestOption[];
  maxLength?: number;
  autoComplete?: string;
}

export interface ServiceCategory {
  id: string;
  label: string;
  description: string;
  icon: IconName;
}

export interface Course {
  id: string;
  title: string;
  audience: string;
  outline: ManagedField<string[]>;
  schedule: ManagedField<string>;
  /** ظرفیت کل و تعداد ثبت‌شده؛ `null` یعنی هنوز اعلام نشده است. */
  capacity: ManagedField<{ total: number | null; registered: number | null }>;
  fee: ManagedField<string | null>;
  status: 'open' | 'full' | 'planned' | 'closed';
}

export interface HealthServiceCopy {
  title: string;
  /** عنوان کوتاه‌تر برای کارت‌ها و منوها. */
  shortTitle: string;
  summary: string;
  /** پاراگراف‌های معرفی خدمت. */
  description: string[];
  /** گروه‌های مخاطب (برای خدماتی که مخاطب مشخص دارند). */
  audience?: string[];
  /** حوزه‌های قابل ارائه (مثلاً حوزه‌های ممیزی). */
  scopes?: ManagedField<string[]>;
  steps: Step[];
  documents: ManagedField<string[]>;
  conditions: ManagedField<string[]>;
  /** مدت زمان تقریبی انجام خدمت. */
  duration: ManagedField<string | null>;
  /** هزینه خدمت. */
  fee: ManagedField<string | null>;
  faqs: Faq[];
  requestTypes: RequestOption[];
  extraFields?: ExtraField[];
  /** سلب مسئولیت حقوقی/اداری که همیشه نمایش داده می‌شود. */
  disclaimer: string;
  /** یادداشت داخلی درباره تطبیق عنوان/فرایند با رویه واقعی (نیازمند تأیید مدیریت). */
  reviewNote?: string;
}

export interface HealthService {
  slug: string;
  icon: IconName;
  category: string;
  status: ServiceStatus;
  /** ترتیب نمایش در فهرست (عدد کوچک‌تر اول). */
  order: number;
  /** عنوان و توضیح متای اختصاصی صفحه (سئو). */
  seo: { title: string; description: string };
  copy: HealthServiceCopy;
  courses?: Course[];
}

